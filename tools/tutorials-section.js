/* ════════════════════════════════════════════════════════════════
   Writes the public homepage section "Learn OrivenAI" (#tutorials) into
   index.html from the ONE tutorial list in js/tutorial-library.js, so the
   homepage and the Dashboard can't drift apart. Static HTML (no JS needed
   to see the cards; prerender copies it into home.html); each card opens
   the shared player (js/ow-ui.js). Placed directly after the assistant
   section. Idempotent: replaces what is between the markers.
   RUN: node tools/tutorials-section.js   (then the SEO pipeline: prerender)
   CHECK: node tools/tutorials-section.js --check
   ════════════════════════════════════════════════════════════════ */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '..');
const INDEX = path.join(ROOT, 'index.html');
const lib = fs.readFileSync(path.join(ROOT, 'js/tutorial-library.js'), 'utf8');
const LIST = vm.runInNewContext(lib.slice(lib.indexOf('var LIST = ['), lib.indexOf('];', lib.indexOf('var LIST = [')) + 2) + ' LIST');
const B = '/assets/films/tutorials/';
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const dur = (s) => Math.floor(s / 60) + ':' + String(Math.round(s % 60)).padStart(2, '0');
const spoken = (s) => { const m = Math.floor(s / 60), r = Math.round(s % 60); return (m ? m + ' min ' : '') + (r ? r + ' s' : ''); };

const card = (t) => `      <li class="ik-tut__item">
        <button type="button" class="ik-tut" data-ow-video="${B}${t.key}.mp4" data-ow-poster="${B}${t.key}.jpg" data-ow-captions="${B}${t.key}.vtt" data-ow-title="${esc(t.name)} tutorial" aria-label="${esc('Play the ' + t.name + ' tutorial, ' + spoken(t.seconds) + ': ' + t.pages.join(', '))}">
          <span class="ik-tut__media"><img src="${B}${t.key}-thumb.webp" alt="" width="960" height="540" loading="lazy" decoding="async"><span class="ik-tut__play" aria-hidden="true"><svg viewBox="0 0 24 24" fill="currentColor"><path d="M8 5.5v13l10.5-6.5z"/></svg></span><span class="ik-tut__dur" aria-hidden="true">${dur(t.seconds)}</span></span>
          <span class="ik-tut__body"><span class="ik-tut__n" aria-hidden="true">${t.n}</span><span class="ik-tut__t">${esc(t.name)}</span><span class="ik-tut__learn">${esc(t.learn)}</span><span class="ik-tut__pages" aria-hidden="true">${t.pages.map(esc).join(' · ')}</span></span>
        </button>
      </li>`;

const SECTION = `<!-- tutorials:start (generated by tools/tutorials-section.js from js/tutorial-library.js — do not edit by hand) -->
<section class="ik-sec ik-tutorials" id="tutorials" aria-labelledby="ik-tut-title">
  <div class="ik-wrap ik-wrap--wide">
    <div class="ik-head ik-head--center" data-reveal="stagger">
      <p class="ik-eyebrow">Tutorials</p>
      <h2 class="ik-h2" id="ik-tut-title">Learn OrivenAI in six short videos.</h2>
      <p class="ik-lead">One tutorial per section, covering every page in it. Recorded in the real app with a sample business; captions on, nothing plays until you choose.</p>
    </div>
    <ul class="ik-tut__grid" role="list">
${LIST.map(card).join('\n')}
    </ul>
  </div>
</section>
<!-- tutorials:end -->
`;

let h = fs.readFileSync(INDEX, 'utf8');
const S = h.indexOf('<!-- tutorials:start'), E = h.indexOf('<!-- tutorials:end -->');
let out;
if (S >= 0 && E > S) out = h.slice(0, S) + SECTION + h.slice(E + '<!-- tutorials:end -->\n'.length);
else {
  const at = h.indexOf('<section class="ik-sec ik-how" id="how"');
  if (at < 0) throw new Error('#how not found');
  out = h.slice(0, at) + SECTION + h.slice(at);
}
if (process.argv.includes('--check')) { if (out !== h) { console.error('tutorials section out of date: run node tools/tutorials-section.js'); process.exit(1); } console.log('tutorials section up to date'); }
else { fs.writeFileSync(INDEX, out); console.log(out === h ? 'Nothing changed' : 'tutorials section written (' + LIST.length + ' cards)'); }
