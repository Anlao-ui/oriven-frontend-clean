/* ════════════════════════════════════════════════════════════════
   The official OrivenAI favicon on every HTML page.

   Every site HTML document (hand-written, generated by tools/seo/build.js,
   prerendered by tools/seo/prerender.js, the app and the admin pages) must
   carry the one standard icon block, with no duplicate or legacy
   ("shortcut icon") references; every referenced file must exist and be the
   right kind and size; the sources that generate pages must carry the block
   so a rebuild keeps it; and a local static server must serve each asset
   with an image / manifest content type.

   SAFE: reads files and starts a static server on 127.0.0.1 only. No network.
   RUN: node tests/favicon.test.js
   ════════════════════════════════════════════════════════════════ */
const fs = require('fs'), path = require('path'), http = require('http');
const ROOT = path.resolve(__dirname, '..');
let pass = 0, fail = 0;
function check(name, ok, info) { ok ? pass++ : fail++; console.log((ok ? 'PASS — ' : 'FAIL — ') + name + (ok || info === undefined ? '' : ' | ' + JSON.stringify(info).slice(0, 700))); }

const BLOCK = [
  '<link rel="icon" href="/favicon.ico" sizes="any">',
  '<link rel="icon" href="/assets/favicon-32.png" type="image/png" sizes="32x32">',
  '<link rel="icon" href="/assets/favicon-48.png" type="image/png" sizes="48x48">',
  '<link rel="apple-touch-icon" href="/assets/apple-touch-icon.png">',
  '<link rel="manifest" href="/site.webmanifest">',
];
const ICON_TAG = /<link\b[^>]*\brel=["'](?:shortcut icon|icon|apple-touch-icon|manifest|mask-icon|apple-touch-icon-precomposed)["'][^>]*>/gi;

// Every site HTML document. Excluded: node_modules, .git, tests (fixtures and
// screenshots) and assets/ (source files of the demo film, not site pages).
function htmlFiles() {
  const out = [];
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      if (['node_modules', '.git', 'tests', 'assets'].includes(e.name) || e.name.startsWith('.')) continue;
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p); else if (e.name.endsWith('.html')) out.push(p);
    }
  })(ROOT);
  return out.sort();
}
const pngSize = (b) => (b.slice(1, 4).toString() === 'PNG' ? [b.readUInt32BE(16), b.readUInt32BE(20)] : null);

const files = htmlFiles();
console.log('\n1. Every HTML page carries the standard icon block (' + files.length + ' pages)');
check('the site has its pages (home, app, Learn, Blog, legal, admin…)', files.length >= 50 && ['index.html', 'app.html', 'privacy.html', 'terms.html', 'refund-policy.html', 'contact.html', 'about.html', 'pricing.html', 'blog.html', path.join('learn', 'index.html'), path.join('blog', 'oriven-ai-is-now-live.html'), path.join('admin', 'index.html')].every((f) => files.includes(path.join(ROOT, f))), files.length);
const bad = [], dup = [], legacy = [];
for (const f of files) {
  const h = fs.readFileSync(f, 'utf8');
  const head = h.slice(0, h.search(/<\/head>/i) + 1 || h.length);
  const tags = (head.match(ICON_TAG) || []).map((t) => t.replace(/\s+/g, ' ').trim());
  const rel = path.relative(ROOT, f);
  if (JSON.stringify(tags) !== JSON.stringify(BLOCK)) bad.push({ rel, tags });
  if (new Set(tags).size !== tags.length) dup.push(rel);
  if (/rel=["']shortcut icon["']/i.test(h)) legacy.push(rel);
  const bodyIcons = (h.slice(head.length).match(ICON_TAG) || []).length;
  if (bodyIcons) bad.push({ rel, inBody: bodyIcons });
}
check('every page: exactly the five standard icon tags, in order, in <head>', bad.length === 0, bad.slice(0, 5));
check('no duplicate icon references on any page', dup.length === 0, dup);
check('no legacy "shortcut icon" references left', legacy.length === 0, legacy);

console.log('\n2. The referenced files exist and are right');
const hrefs = Array.from(new Set(BLOCK.map((t) => t.match(/href="([^"]+)"/)[1])));
const missing = hrefs.filter((h) => !fs.existsSync(path.join(ROOT, h)));
check('every referenced file exists: ' + hrefs.join(', '), missing.length === 0, missing);
for (const [file, size] of [['assets/favicon-32.png', 32], ['assets/favicon-48.png', 48], ['assets/apple-touch-icon.png', 180], ['assets/orivenlogo-192.png', 192], ['assets/orivenlogo-512.png', 512]]) {
  const s = fs.existsSync(path.join(ROOT, file)) ? pngSize(fs.readFileSync(path.join(ROOT, file))) : null;
  check(file + ' is a ' + size + '×' + size + ' PNG', !!s && s[0] === size && s[1] === size, s);
}
const ico = fs.readFileSync(path.join(ROOT, 'favicon.ico'));
const n = ico.readUInt16LE(4), sizes = [];
for (let i = 0; i < n; i++) { const e = 6 + i * 16; const w = ico.readUInt8(e) || 256, len = ico.readUInt32LE(e + 8), off = ico.readUInt32LE(e + 12); const s = pngSize(ico.slice(off, off + len)); sizes.push(s && s[0] === w ? w : 'bad'); }
check('favicon.ico is a valid icon with 16, 32 and 48 px images', ico.readUInt16LE(0) === 0 && ico.readUInt16LE(2) === 1 && JSON.stringify(sizes) === '[16,32,48]', sizes);
let man = null; try { man = JSON.parse(fs.readFileSync(path.join(ROOT, 'site.webmanifest'), 'utf8')); } catch (_) { /* reported below */ }
check('site.webmanifest is valid JSON named OrivenAI, with 192 and 512 px icons that exist', !!man && man.name === 'OrivenAI' && Array.isArray(man.icons) && ['192x192', '512x512'].every((s) => man.icons.some((i) => i.sizes === s && fs.existsSync(path.join(ROOT, i.src)))), man);

const hdr = fs.readFileSync(path.join(ROOT, '_headers'), 'utf8').replace(/\r\n/g, '\n');
check('_headers serves site.webmanifest as application/manifest+json (Netlify’s default is octet-stream, and pages send nosniff)', /^\/site\.webmanifest\n\s+Content-Type: application\/manifest\+json/m.test(hdr));

console.log('\n3. Regeneration keeps the block');
const build = fs.readFileSync(path.join(ROOT, 'tools/seo/build.js'), 'utf8').replace(/\r\n/g, '\n');
const idx = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8').replace(/\r\n/g, '\n');
check('tools/seo/build.js (Learn, Blog, solution and product-intent pages) writes the block', BLOCK.every((t) => build.includes(t)));
check('index.html (source of the prerendered public pages: pricing, legal, contact, about…) carries the block', BLOCK.every((t) => idx.includes(t)));

console.log('\n4. Served locally with the right content types');
const TYPES = { '.ico': 'image/x-icon', '.png': 'image/png', '.webmanifest': 'application/manifest+json' };
const server = http.createServer((q, r) => {
  const f = path.join(ROOT, decodeURIComponent(q.url.split('?')[0]));
  if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { r.writeHead(404); return r.end(); }
  r.writeHead(200, { 'Content-Type': TYPES[path.extname(f)] || 'application/octet-stream' }); fs.createReadStream(f).pipe(r);
}).listen(0, '127.0.0.1', async () => {
  const port = server.address().port;
  const got = [];
  for (const h of hrefs) {
    const res = await new Promise((ok) => http.get({ host: '127.0.0.1', port, path: h }, (r) => { const c = []; r.on('data', (d) => c.push(d)); r.on('end', () => ok({ h, status: r.statusCode, type: r.headers['content-type'], bytes: Buffer.concat(c).length })); }).on('error', (e) => ok({ h, err: e.message })));
    got.push(res);
  }
  check('each asset is served (200, image or manifest type, not empty)', got.every((g) => g.status === 200 && /image|manifest/.test(g.type || '') && g.bytes > 0), got);
  server.close();
  console.log(`\n${pass + fail} checks run, ${pass} passed, ${fail} failed.`);
  process.exit(fail ? 1 : 0);
});
